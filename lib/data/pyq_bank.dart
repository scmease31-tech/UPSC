import '../models/pyq_question.dart';

/// ──────────────────────────────────────────────────────────────────────────────
/// PyqBank — the offline seed bank for the Previous Year Questions tab.
///
/// Provenance is explicit, and shown in the UI:
///   • source: 'UPSC'         — question asked in that year's paper.
///   • source: 'UPSC Pattern' — written to that year's syllabus emphasis and
///                              question style; use it as practice, not as a
///                              record of what was asked.
///
/// The tab merges this bank with the live `pyqs` Firestore collection, which is
/// harvested verbatim (with the exam year) from the PYQ block Drishti appends to
/// its daily articles — so the bank keeps growing without an app update.
/// ──────────────────────────────────────────────────────────────────────────────
class PyqBank {
  PyqBank._();

  static List<PyqQuestion>? _cache;

  /// Every seeded question, newest year first.
  static List<PyqQuestion> get all {
    return _cache ??= [..._prelims, ..._mains]..sort((a, b) => b.year.compareTo(a.year));
  }

  /// Years present in the seed bank, descending.
  static List<int> get years =>
      all.map((q) => q.year).toSet().toList()..sort((a, b) => b.compareTo(a));
}

// ── shorthand builders ───────────────────────────────────────────────────────

PyqQuestion _p(
  String id,
  int year,
  String subject,
  String question,
  List<String> options,
  int answer,
  String explanation, {
  String source = 'UPSC',
}) =>
    PyqQuestion(
      id: id,
      year: year,
      type: PyqType.prelims,
      subject: subject,
      paper: 'Prelims GS-I',
      question: question,
      options: options,
      answer: answer,
      explanation: explanation,
      source: source,
    );

PyqQuestion _m(
  String id,
  int year,
  String subject,
  String paper,
  int marks,
  String question,
  String approach, {
  String source = 'UPSC',
}) =>
    PyqQuestion(
      id: id,
      year: year,
      type: PyqType.mains,
      subject: subject,
      paper: paper,
      marks: marks,
      question: question,
      approach: approach,
      source: source,
    );

